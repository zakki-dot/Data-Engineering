# Step 6: Offs/Ons Bias Analysis
print("\n" + "="*50)
print("OFFS/ONS BIAS ANALYSIS")
print("="*50)

total_offs = stops_df['offs'].sum()
total_ons = stops_df['ons'].sum()
total_passengers = total_offs + total_ons
system_offs_prop = total_offs / total_passengers if total_passengers > 0 else 0
system_ons_prop = total_ons / total_passengers if total_passengers > 0 else 0

print(f"System totals: offs={total_offs:,}, ons={total_ons:,}")
print(f"System proportions: offs={system_offs_prop:.4f}, ons={system_ons_prop:.4f}")

offs_ons_biased = []
alpha = 0.05

print(f"\nTesting offs/ons bias (χ² test, α={alpha}):")
print("Vehicle | Offs | Ons | Offs% | Ons% | p-value | Biased")
print("-" * 65)

for vehicle_id, group in stops_df.groupby('vehicle_number'):
    vehicle_offs = int(group['offs'].sum())
    vehicle_ons = int(group['ons'].sum())
    vehicle_total = vehicle_offs + vehicle_ons

    if vehicle_total == 0:
        continue

    vehicle_offs_prop = vehicle_offs / vehicle_total
    vehicle_ons_prop = vehicle_ons / vehicle_total

    # Chi-square test
    contingency_table = [
        [vehicle_offs, vehicle_ons],
        [total_offs - vehicle_offs, total_ons - vehicle_ons]
    ]

    chi2, p_value, dof, expected = chi2_contingency(contingency_table)

    # Check if expected frequencies are adequate
    if (expected < 5).any():
        continue

    is_biased = p_value < alpha
    bias_indicator = "*" if is_biased else ""

    print(f"{vehicle_id:7} | {vehicle_offs:4} | {vehicle_ons:3} | {vehicle_offs_prop*100:5.2f}% | "
          f"{vehicle_ons_prop*100:5.2f}% | {p_value:.6f} | {bias_indicator}")

    if is_biased:
        bias_type = "more offs" if vehicle_offs_prop > system_offs_prop else "more ons"
        offs_ons_biased.append({
            'vehicle_id': vehicle_id,
            'p_value': p_value,
            'bias_type': bias_type,
            'offs_prop': vehicle_offs_prop,
            'ons_prop': vehicle_ons_prop
        })

print(f"\nVehicles with offs/ons bias (p < {alpha}): {len(offs_ons_biased)}")
if offs_ons_biased:
    print("\nOffs/Ons biased vehicles:")
    for vehicle in sorted(offs_ons_biased, key=lambda x: x['p_value']):
        print(f"  Vehicle {vehicle['vehicle_id']}: p={vehicle['p_value']:.6f} ({vehicle['bias_type']})")