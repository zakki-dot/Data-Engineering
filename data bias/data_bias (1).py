import pandas as pd
from bs4 import BeautifulSoup
from datetime import datetime, timedelta
from io import StringIO
from scipy.stats import binomtest, ttest_1samp, chi2_contingency

# Step 1: Correctly parse HTML with multiple trip sections
print("Loading and parsing HTML file...")
with open("trimet_stopevents_2022-12-07.html", "r", encoding="utf-8") as f:
    raw_html = f.read()

soup = BeautifulSoup(raw_html, "html.parser")

# Find all headings for each trip (this was the key missing piece)
headings = soup.find_all("h2", string=lambda t: t and t.strip().startswith("Stop events for PDX_TRIP"))

frames = []
base_date = datetime.strptime("2022-12-07", "%Y-%m-%d")

print(f"Found {len(headings)} trip sections...")

for hdr in headings:
    text = hdr.get_text(strip=True)
    parts = text.split()
    trip = parts[-1]  # Extract trip ID

    # Find the table after this heading
    tbl = hdr.find_next_sibling("table")
    if tbl is None:
        tbl = hdr.find_next("table")
    if tbl is None:
        print(f"Warning: no table found after heading '{text}'")
        continue

    # Parse the table
    df_temp = pd.read_html(StringIO(str(tbl)))[0]

    # Handle missing values in arrive_time
    df_temp = df_temp.dropna(subset=['arrive_time'])  # Remove rows with missing arrive_time
    df_temp["tstamp"] = df_temp["arrive_time"].apply(
        lambda s: base_date + timedelta(seconds=int(s)) if pd.notna(s) else None
    )

    # Select relevant columns and add trip_id
    # Make sure we have all required columns
    required_cols = ["vehicle_number", "tstamp", "location_id", "ons", "offs"]
    if all(col in df_temp.columns for col in required_cols):
        sub_df = df_temp[required_cols].copy()
        sub_df.insert(0, "trip_id", trip)
        frames.append(sub_df)
    else:
        print(f"Warning: Missing required columns in trip {trip}, skipping...")

# Combine all trips
if frames:
    stops_df = pd.concat(frames, ignore_index=True)
    # Remove any remaining rows with missing timestamps
    stops_df = stops_df.dropna(subset=['tstamp'])
else:
    print("Error: No valid trip data found!")
    exit()

print(f"Loaded {len(stops_df):,} stop events")
expected_count = 93912
if len(stops_df) == expected_count:
    print("✓ Loaded expected 93,912 records")
else:
    print(f"⚠ Expected {expected_count:,} but got {len(stops_df):,}")
    print("  This may be due to data cleaning or missing values")

