# Step 4: Find vehicles with biased boarding data
print("\n" + "="*50)
print("BOARDING BIAS ANALYSIS")
print("="*50)

# Calculate system-wide boarding rate
system_p = (stops_df['ons'] >= 1).mean()
print(f"System-wide proportion of stops with boardings: {system_p:.4f} ({system_p * 100:.2f}%)")

# Test each vehicle for bias
results = []
biased_vehicles = []

print(f"\nTesting {stops_df['vehicle_number'].nunique()} vehicles...")
print("Vehicle | Stops | Boarding_Stops | Rate | p-value | Biased")
print("-" * 65)

for vehicle_id, group in stops_df.groupby('vehicle_number'):
    total_stops = len(group)
    boarding_stops = (group['ons'] >= 1).sum()
    boarding_rate = boarding_stops / total_stops if total_stops > 0 else 0

    # Perform binomial test
    test = binomtest(k=boarding_stops, n=total_stops, p=system_p, alternative='two-sided')
    p_value = test.pvalue

    is_biased = p_value < 0.05
    bias_indicator = "*" if is_biased else ""

    print(f"{vehicle_id:7} | {total_stops:5} | {boarding_stops:14} | {boarding_rate:5.3f} | {p_value:.6f} | {bias_indicator}")

    results.append({
        'vehicle_id': vehicle_id,
        'total_stops': total_stops,
        'boarding_stops': boarding_stops,
        'boarding_rate': boarding_rate,
        'p_value': p_value
    })

    if is_biased:
        biased_vehicles.append({
            'vehicle_id': vehicle_id,
            'p_value': p_value,
            'boarding_rate': boarding_rate
        })

print(f"\nVehicles with biased boarding data (p < 0.05): {len(biased_vehicles)}")
if biased_vehicles:
    print("\nBiased vehicles (sorted by p-value):")
    for vehicle in sorted(biased_vehicles, key=lambda x: x['p_value']):
        direction = "HIGH" if vehicle['boarding_rate'] > system_p else "LOW"
        print(f"  Vehicle {vehicle['vehicle_id']}: p={vehicle['p_value']:.6f}, rate={vehicle['boarding_rate']:.3f} ({direction})")

